"""Replace hand-written hit targets in the stylesheet with the tokens it publishes.

One of the three design-source gates refuses a `44px` or `28px` written into a
`min-height`, `min-width`, `width` or `height` rule, because
`docs/design-tokens.json` already states both numbers once, as
`control.touchPt` 44 and `control.macosPt` 28. `styles.css` restates them 52
times, and the copy that drifts is the copy that was typed by hand.

This is the one part of the stylesheet debt that is safe to convert without
looking at a rendered page: every substitution replaces `44px` with a token
whose value is `44px` and `28px` with a token whose value is `28px`. The
computed value of every rule is identical before and after, so no visual change
is possible and no browser check can find a difference. That is why this script
exists alone and why the radius and colour work is not in it: a radius has no
exact role for nine of its values, and a category colour has no role at all, so
converting either would change what a person sees.

Only the size is replaced. A declaration keeps its property, so `min-height:
44px` stays a floor and `width: 28px` stays a width.

Run it from the repository root:

    python3 scripts/src/tokenise-hit-targets.py
    python3 scripts/src/tokenise-hit-targets.py --check
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
STYLESHEET = ROOT / "apps" / "control-plane" / "ui" / "src" / "styles.css"
CHAT_STYLESHEET = ROOT / "apps" / "control-plane" / "ui" / "src" / "chat.css"
TOKENS = ROOT / "docs" / "design-tokens.json"

BEGIN = "/* --- BEGIN GENERATED BY scripts/src/build-web.mjs FROM docs/design-tokens.json --- */"
END = "/* --- END GENERATED BY scripts/src/build-web.mjs FROM docs/design-tokens.json --- */"

# The property list is the gate's own, so the script and the gate cannot
# disagree about what counts as a hit target.
HIT_TARGET = re.compile(
    r"(?<![-\w])(min-height|min-width|width|height):\s*([^;]*\b(44|28)px\b[^;]*);"
)


def tokens(document: dict) -> dict[int, str]:
    """Pixel value to token name, read from the document rather than restated."""
    control = document["control"]
    return {
        int(control["touchPt"]): "--control-touch",
        int(control["macosPt"]): "--control-macos",
    }


def convert(text: str, known: dict[int, str]) -> tuple[str, int]:
    """Rewrite every hand-written target outside the generated region."""
    first, last = text.index(BEGIN), text.index(END)
    head, generated, tail = text[:first], text[first : last + len(END)], text[last + len(END) :]

    count = 0

    def replace(match: re.Match[str]) -> str:
        nonlocal count
        property_name, body, pixels = match.group(1), match.group(2), int(match.group(3))
        token = known.get(pixels)
        if token is None:
            return match.group(0)
        count += 1
        # The negative lookbehind is the gate's own: it stops `44px` inside
        # `144px` from being replaced. Built outside the f-string because a
        # backslash cannot appear in one.
        pattern = r"(?<![-\w])" + str(pixels) + r"px\b"
        rewritten = re.sub(pattern, "var(" + token + ")", body)
        return property_name + ": " + rewritten + ";"

    return head + generated + HIT_TARGET.sub(replace, tail), count


def main(argv: list[str]) -> int:
    check = "--check" in argv
    known = tokens(json.loads(TOKENS.read_text(encoding="utf-8")))
    total = 0
    for path in (STYLESHEET, CHAT_STYLESHEET):
        text = path.read_text(encoding="utf-8")
        if BEGIN not in text:
            continue
        converted, count = convert(text, known)
        total += count
        if check:
            if converted != text:
                print(f"{path} still holds {count} hand-written hit targets", file=sys.stderr)
                return 1
            continue
        path.write_text(converted, encoding="utf-8")
    if check:
        print(f"no hand-written hit targets remain; tokens {sorted(set(known.values()))}")
        return 0
    print(f"converted {total} hit targets to {sorted(set(known.values()))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
