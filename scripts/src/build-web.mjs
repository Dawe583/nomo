/**
 * Writes the web custom properties from `docs/design-tokens.json`, then runs the
 * Vite build and copies the two files that ship beside the bundle.
 *
 * `scripts/src/generate-swift-tokens.mjs` is the other consumer of the same
 * document, so a token exists once and a change to the appearance is a change to
 * the document. Nothing in the generated region is written that the document
 * does not carry, which is what lets `scripts/src/design-source.test.mjs` fail a
 * hand edit in the stylesheet: the stylesheet is a function of its input.
 *
 * The output is byte identical on a second run. There is no timestamp, no
 * iteration over anything unordered, and every list is assembled from the
 * document's own key order, so a regeneration that differs is a real change
 * rather than a build artefact.
 *
 * The custom property names are older than the document. Every component rule in
 * the stylesheet already resolves them, and an unresolved custom property drops
 * the declaration using it with nothing in the log, so the mapping below is the
 * direction that cannot be changed without touching every rule.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { copyFile, mkdir, rm } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const GENERATOR = "scripts/src/build-web.mjs";
const SOURCE = "docs/design-tokens.json";
const STYLESHEET = "apps/control-plane/ui/src/styles.css";

export const BEGIN = `/* --- BEGIN GENERATED BY ${GENERATOR} FROM ${SOURCE} --- */`;
export const END = `/* --- END GENERATED BY ${GENERATOR} FROM ${SOURCE} --- */`;

/**
 * The document's semantic role to the custom property the component rules
 * already read. Written out rather than derived, because the names differ: the
 * document calls text `text` and the stylesheet calls it `--ink`, and a reader
 * has to be able to see that the difference is deliberate.
 */
const ROLE_PROPERTIES = [
  ["canvas", "--canvas"],
  ["surface", "--surface"],
  ["raised", "--raised"],
  ["text", "--ink"],
  ["muted", "--muted"],
  ["separator", "--line"],
  ["accent", "--action"],
  ["onAccent", "--action-text"],
  ["danger", "--danger"],
  ["good", "--good"],
  ["focus", "--focus"],
  // The syntax roles are named for what they mark rather than for their hue,
  // because a component asks for "this is a keyword" and not "this is that
  // brown". A hue-derived name would be the same value the stylesheet already
  // had as a literal, with the drift moved rather than removed.
  ["syntaxKeyword", "--syntax-keyword"],
  ["syntaxString", "--syntax-string"],
  ["syntaxNumber", "--syntax-number"],
];

/** A CSS custom property declaration at a fixed indent. */
const declare = (name, value, indent = "  ") =>
  `${indent}${name}: ${value};`;

/**
 * The document's roles as declarations for one appearance.
 *
 * A role with no value in the requested appearance is an error rather than a
 * skipped line, so a role that exists in one appearance only is visible instead
 * of silently inheriting the other appearance's value.
 */
function roleDeclarations(roles, appearance) {
  const lines = [];
  for (const [role, property] of ROLE_PROPERTIES) {
    const value = roles[role]?.[appearance];
    if (value === undefined) {
      throw new Error(
        `${SOURCE} has no ${appearance} value for the ${role} role, so ${property} has no value to write`,
      );
    }
    lines.push(declare(property, value));
  }
  return lines;
}

/** The shadow roles, which carry both appearances and keep their own names. */
function shadowDeclarations(shadows, appearance) {
  return Object.entries(shadows).map(([role, values]) => {
    const value = values?.[appearance];
    if (value === undefined) {
      throw new Error(
        `${SOURCE} has no ${appearance} value for the ${role} shadow role`,
      );
    }
    return declare(`--shadow-${role}`, value);
  });
}

/**
 * The scrim roles, which carry both appearances under a `--scrim-` name.
 *
 * Separate from the shadow declarations because the family differs, not only
 * the prefix: a shadow is an offset and a blur, a scrim is a veil. A role in
 * the shadow family is required to have both of those, and a scrim has neither.
 */
function scrimDeclarations(scrims, appearance) {
  return Object.entries(scrims).map(([role, values]) => {
    const value = values?.[appearance];
    if (value === undefined) {
      throw new Error(
        `${SOURCE} has no ${appearance} value for the ${role} scrim role`,
      );
    }
    return declare(`--scrim-${role}`, value);
  });
}

/** The whole generated region, markers included, as text. */
export function renderWebTokens(tokens) {
  const roles = tokens.colour.roles;
  const shadows = tokens.colour.shadow.roles;
  // A modal scrim is a full-bleed veil rather than a drop shadow, so it is
  // declared from its own section. A scrim put in the shadow family would
  // inherit that family's rule that every role carries an offset and a blur,
  // which a veil has neither of.
  const scrims = tokens.colour.scrim?.roles ?? {};
  const type = tokens.type;
  const mobile = type.webMobileRoot;
  if (
    typeof mobile?.maxWidthPx !== "number" ||
    typeof mobile?.rootPx !== "number"
  ) {
    throw new Error(
      `${SOURCE} has no type.webMobileRoot, so the mobile composition has no root size to write`,
    );
  }
  const radii = tokens.radii.roles;

  // A role added to the document without a web name, or a name left behind
  // after a role is renamed, is a defect the stylesheet cannot show on its own.
  const documented = Object.keys(roles);
  const named = ROLE_PROPERTIES.map(([role]) => role);
  const unnamed = documented.filter((role) => !named.includes(role));
  const gone = named.filter((role) => !documented.includes(role));
  if (unnamed.length > 0 || gone.length > 0) {
    throw new Error(
      `${SOURCE} roles and the web mapping disagree: no custom property for ${unnamed.join(", ") || "none"}, and no document role for ${gone.join(", ") || "none"}`,
    );
  }

  // The mapping is emitted as a list rather than a sentence, because a reader
  // looking up one name has to find it without reading the whole comment.
  const width = Math.max(...ROLE_PROPERTIES.map(([role]) => role.length));
  const mapping = ROLE_PROPERTIES.map(
    ([role, property]) => `${role.padEnd(width)} -> ${property}`,
  );
  const shadowNames = Object.keys(shadows);

  const light = [
    `  font-family: var(--font-interface);`,
    `  font-size: ${type.webBodyPx}px;`,
    `  line-height: ${type.webBodyLineHeight};`,
    `  color: var(--ink);`,
    `  background: var(--canvas);`,
    "",
    `  /* Colour. */`,
    ...roleDeclarations(roles, "light"),
    "",
    `  /* Elevation. */`,
    ...shadowDeclarations(shadows, "light"),
    ...scrimDeclarations(scrims, "light"),
    "",
    `  /* Type. The interface face is the platform UI font, resolved by the`,
    `     platform, and the code face is the platform monospaced face. */`,
    declare("--font-interface", type.interfaceFont),
    declare("--font-code", type.codeFont),
    "",
    `  /* Spacing, the 4 point rhythm, named by step. */`,
    ...tokens.spacing.rhythm.map((value, index) =>
      declare(`--space-${index + 1}`, `${value}px`),
    ),
    "",
    `  /* Radii, named for what they round. A nested element takes a smaller`,
    `     role than its container. */`,
    ...Object.entries(radii).map(([role, value]) =>
      declare(`--radius-${role}`, `${value}px`),
    ),
    "",
    `  /* Control hit targets, a floor. The touch role is the web conversion of`,
    `     the point rule, so the web and the phone agree on one number. */`,
    declare("--control-touch", `${tokens.control.webTouchPx}px`),
    declare("--control-macos", `${tokens.control.macosPt}px`),
  ];

  const dark = [
    `  /* Colour. */`,
    ...roleDeclarations(roles, "dark"),
    "",
    `  /* Elevation. */`,
    ...shadowDeclarations(shadows, "dark"),
    ...scrimDeclarations(scrims, "dark"),
    "",
    `  /* The one declaration the document does not carry. It tells the browser`,
    `     which built-in widget colours to draw, which is a property of the page`,
    `     rather than a design value, so it has no token. */`,
    `  color-scheme: dark;`,
  ];

  return [
    BEGIN,
    `/* Semantic role to custom property. The document names a role for what it`,
    `   means and the stylesheet names it for what it paints, so the two`,
    `   vocabularies differ and the difference is deliberate.`,
    ``,
    `   ${mapping.join("\n   ")}`,
    ``,
    `   A shadow role keeps the document's own name:`,
    `   ${shadowNames.map((name) => `--shadow-${name}`).join(", ")}`,
    ``,
    `   A hand edit in this region is a defect, not a preference: the next`,
    `   build overwrites it and scripts/src/design-source.test.mjs compares`,
    `   the two byte for byte. Change ${SOURCE} and rebuild. */`,
    `:root {`,
    ...light,
    `}`,
    `:root[data-theme="dark"] {`,
    ...dark,
    `}`,
    `/* The mobile root size. It is emitted here rather than written beside`,
    `   the layout rules that need it, because it is a type size and the`,
    `   document is its only owner. The block follows the two appearances so`,
    `   that it overrides both. */`,
    `@media (max-width: ${mobile.maxWidthPx}px) {`,
    `  :root {`,
    `    font-size: ${mobile.rootPx}px;`,
    `  }`,
    `}`,
    END,
    ``,
  ].join("\n");
}

/**
 * Replaces the marked region of the stylesheet with the current document.
 * Returns the text the stylesheet now holds.
 */
export function generateWebTokens(root = new URL("../../", import.meta.url)) {
  const source = readFileSync(new URL(SOURCE, root), "utf8");
  const block = renderWebTokens(JSON.parse(source));
  const target = new URL(STYLESHEET, root);
  const stylesheet = readFileSync(target, "utf8");
  const first = stylesheet.indexOf(BEGIN);
  const last = stylesheet.indexOf(END);
  if (first === -1 || last === -1) {
    throw new Error(
      `${STYLESHEET} has no generated region: the lines "${BEGIN}" and "${END}" must both be present, because the generator replaces what is between them rather than guessing where the tokens go`,
    );
  }
  if (last < first) {
    throw new Error(`${STYLESHEET} has the end marker before the start marker`);
  }
  const next =
    stylesheet.slice(0, first) + block + stylesheet.slice(last + END.length + 1);
  writeFileSync(target, next);
  return next;
}

/** The Vite build and the two files that ship beside the bundle. */
async function build() {
  const root = new URL("../../", import.meta.url);
  await rm(new URL("../../dist/web/", import.meta.url), {
    recursive: true,
    force: true,
  });
  // Vercel invokes this file directly; pnpm scripts additionally provide npm_execpath.
  const packageManager = process.env.npm_execpath;
  const result = spawnSync(
    packageManager ? process.execPath : "pnpm",
    [
      ...(packageManager ? [packageManager] : []),
      "--filter",
      "@void/control-plane-ui",
      "build",
    ],
    { cwd: root, stdio: "inherit" },
  );
  if (result.status !== 0) process.exit(result.status ?? 1);
  const output = new URL("../../dist/web/", import.meta.url);
  await mkdir(output, { recursive: true });
  for (const name of ["icon.svg", "manifest.webmanifest"])
    await copyFile(
      new URL(`../../apps/control-plane/web/${name}`, import.meta.url),
      new URL(name, output),
    );
  console.log("VOID web build ready: dist/web");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateWebTokens();
  await build();
}
