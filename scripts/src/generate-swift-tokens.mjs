/**
 * Writes the Swift token module from `docs/design-tokens.json`.
 *
 * The web custom properties and this file are two consumers of one document, so
 * a token exists once and a change to the appearance is a change to the
 * document. Nothing is written that the document does not carry, which is what
 * makes `scripts/src/design-source-swift.test.mjs` able to fail a hand edit in
 * the consumer: the consumer is a function of its input.
 *
 * The output is byte identical on a second run. There is no timestamp, no
 * iteration over anything unordered, and the file is assembled from the
 * document's own key order, so a regeneration that differs is a real change.
 *
 * The module imports Foundation and nothing else. It carries values, not
 * colours: turning a role into a `Color` is `NomoPalette`'s job in the same
 * target, because only that file knows how the two platforms spell a semantic
 * background.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const GENERATOR = "scripts/src/generate-swift-tokens.mjs";
const SOURCE = "docs/design-tokens.json";
const TARGET =
  "apps/apple/NomoDesignSystem/Sources/NomoDesignSystem/NomoTokens.generated.swift";

const BEGIN = `// --- BEGIN GENERATED BY ${GENERATOR} FROM ${SOURCE} ---`;
const END = `// --- END GENERATED BY ${GENERATOR} FROM ${SOURCE} ---`;

const HEADER = [
  `// Generated by ${GENERATOR} from ${SOURCE}. Do not edit.`,
  "//",
  "// A hand edit here is a defect, not a preference: the next run of the",
  "// generator overwrites this file, and",
  "// scripts/src/design-source-swift.test.mjs",
  "// compares the two byte for byte. Change the document and regenerate.",
  "//",
  `// The document is the contract: ${SOURCE}, and the appearance it`,
  "// implements is docs/APPLE-DESIGN-SYSTEM.md.",
].join("\n");

/**
 * Words that cannot be a case name. A document key that needs quoting would
 * otherwise produce a file that does not compile, and the failure would be a
 * compile error in generated code, which reads as someone else's mistake.
 */
const RESERVED = new Set(
  `Any Protocol Self Type actor all any as associatedtype associativity break case catch class continue
   convenience default defer deinit didSet distributed do dynamic else enum extension fallthrough false
   fileprivate final for func get guard if import in indirect infix init inout internal is isolated lazy
   left let macro mutating nil noasync nonisolated nonmutating open operator optional override package
   postfix precedence precedencegroup prefix private protocol public repeat required rethrows return right
   self set some static struct subscript super switch throw throws true try typealias unowned var weak
   where while willSet`.split(/\s+/),
);

/** A document key used as a Swift identifier, refusing anything that needs quoting. */
function identifier(key) {
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(key) || RESERVED.has(key)) {
    throw new Error(
      `${SOURCE}: ${JSON.stringify(key)} is not a usable Swift identifier`,
    );
  }
  return key;
}

/** One `#rrggbb` or `#rrggbbaa` value as its four channels. */
function channels(value) {
  const match = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i.exec(value);
  if (!match) {
    throw new Error(`${SOURCE}: ${JSON.stringify(value)} is not #rrggbb`);
  }
  const packed = match[1] + (match[2] ?? "ff");
  return {
    red: parseInt(packed.slice(0, 2), 16),
    green: parseInt(packed.slice(2, 4), 16),
    blue: parseInt(packed.slice(4, 6), 16),
    alpha: parseInt(packed.slice(6, 8), 16),
  };
}

/**
 * A channel as a Swift `Double` literal.
 *
 * Six decimals is the resolution the widest colour distance in the document
 * can lose and still clear its contrast minimum, and the fixed width means the
 * text is identical on every machine.
 */
function literal(value) {
  const fixed = Math.round(value * 1e6) / 1e6;
  const text = fixed.toFixed(6).replace(/0+$/, "");
  return text.endsWith(".") ? `${text}0` : text;
}

/** A `CGFloat` list, in the document's own order. */
const list = (values) => `[${values.map(literal).join(", ")}]`;

/** A wrapped generated section, so a reader and a test can find one by name. */
const section = (name, body) =>
  [
    `// --- BEGIN GENERATED SECTION: ${name} ---`,
    body,
    `// --- END GENERATED SECTION: ${name} ---`,
  ].join("\n");

/** The two appearances the document carries, spelled once for every section. */
const APPEARANCES = ["light", "dark"];

/**
 * A document note as doc-comment lines, wrapped to the width the hand written
 * Swift in this repository uses. A note that arrives as one long line is a note
 * nobody reads in a diff.
 */
function comment(text, indent = "") {
  const lines = [];
  for (const paragraph of text.split("\n")) {
    let line = "";
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      if (line && `${line} ${word}`.length + indent.length > 76) {
        lines.push(`${indent}/// ${line}`);
        line = word;
      } else {
        line = line ? `${line} ${word}` : word;
      }
    }
    lines.push(`${indent}/// ${line}`);
  }
  return lines;
}

/** The platforms the document quotes the type ramp for, in its own order. */
const PLATFORMS = ["ios", "macos"];

/** The colour roles, as a role enum with per-appearance components. */
function colours(tokens) {
  const roles = Object.entries(tokens.colour.roles);
  const cases = roles
    .map(([key, role]) => {
      const notes = [];
      if (role.adjusted) {
        notes.push(
          ...comment(role.adjusted, "    "),
          "    ///",
          "    /// The value recorded here is the one that was measured, not the",
          "    /// platform's default. The reason it moved is the point.",
        );
      }
      if (role.decorative) {
        notes.push(
          "    /// Decorative. It separates, it never carries meaning, so no",
          "    /// contrast pair may be measured against it.",
        );
      }
      const text = [...notes, `    case ${identifier(key)}`].join("\n");
      return notes.length > 0 ? `\n${text}` : text;
    })
    .join("\n");
  const systemName = roles
    .map(
      ([key, role]) => `        case .${key}: ${JSON.stringify(role.system)}`,
    )
    .join("\n");
  const components = APPEARANCES.map((appearance) => {
    const body = roles
      .map(
        ([key, role]) =>
          `        case .${key}: NomoColorComponents(red: ${literal(channels(role[appearance]).red / 255)}, green: ${literal(channels(role[appearance]).green / 255)}, blue: ${literal(channels(role[appearance]).blue / 255)}, alpha: ${literal(channels(role[appearance]).alpha / 255)})`,
      )
      .join("\n");
    return [
      `    /// The ${appearance} appearance components, from the document.`,
      `    var ${appearance}: NomoColorComponents {`,
      "        switch self {",
      body,
      "        }",
      "    }",
    ].join("\n");
  }).join("\n\n");
  return section(
    "NomoColorRole",
    [
      "/// A colour role, and the components the document records for each",
      "/// appearance.",
      "///",
      "/// A role is what a surface names, never a colour. The platform's own",
      "/// semantic colour is the value wherever the platform has one, so Increase",
      "/// Contrast and Reduce Transparency keep working, and the components here",
      "/// are what the web reads and what the contrast gate measures.",
      "public enum NomoColorRole: String, CaseIterable, Sendable {",
      cases,
      "}",
      "",
      "public extension NomoColorRole {",
      "    /// The platform's own semantic colour the role stands for, spelled the",
      "    /// way the document spells it. `NomoPalette` is what turns it into a",
      "    /// `Color`.",
      "    var systemName: String {",
      "        switch self {",
      systemName,
      "        }",
      "    }",
      "",
      "    /// The components in one appearance.",
      "    func components(for appearance: NomoAppearance) -> NomoColorComponents {",
      "        switch appearance {",
      "        case .light: light",
      "        case .dark: dark",
      "        }",
      "    }",
      "",
      "    /// Whether the role only separates. A decorative role carries no",
      "    /// meaning, so no contrast pair may be measured against it.",
      "    var isDecorative: Bool {",
      "        switch self {",
      ...roles
        .filter(([, role]) => role.decorative)
        .map(([key]) => `        case .${key}: true`),
      "        default: false",
      "        }",
      "    }",
      "",
      components,
      "}",
    ].join("\n"),
  );
}

/** The shadow roles, kept as the document's own strings. */
function shadows(tokens) {
  const roles = Object.entries(tokens.colour.shadow.roles);
  return section(
    "NomoShadowRole",
    [
      "/// A shadow role, as the document's string in each appearance.",
      "///",
      "/// These are recorded rather than used on the Apple platforms, where the",
      "/// system bars already separate the functional layer. They exist so no",
      "/// component holds an alpha inline while the web still needs them.",
      "public enum NomoShadowRole: String, CaseIterable, Sendable {",
      ...roles.map(([key]) => `    case ${identifier(key)}`),
      "}",
      "",
      "public extension NomoShadowRole {",
      ...APPEARANCES.flatMap((appearance) => [
        `    /// The ${appearance} appearance value, from the document.`,
        `    var ${appearance}: String {`,
        "        switch self {",
        ...roles.map(
          ([key, role]) =>
            `        case .${key}: ${JSON.stringify(role[appearance])}`,
        ),
        "        }",
        "    }",
        "",
      ]),
      "    /// The value in one appearance.",
      "    func value(for appearance: NomoAppearance) -> String {",
      "        switch appearance {",
      "        case .light: light",
      "        case .dark: dark",
      "        }",
      "    }",
      "}",
    ]
      .join("\n")
      .replace(/\n+$/, ""),
  );
}

/** The type ramp, per platform, with the weights the document uses. */
function type(tokens) {
  const roles = Object.entries(tokens.type.roles);
  const weights = [
    ...new Set(
      roles.flatMap(([, role]) =>
        PLATFORMS.flatMap((platform) => {
          const metrics = role[platform];
          return [metrics.weight, metrics.emphasised].filter(Boolean);
        }),
      ),
    ),
  ];
  const metrics = (platform) =>
    roles
      .map(([key, role]) => {
        const value = role[platform];
        const emphasised =
          value.emphasised === undefined
            ? "nil"
            : `.${identifier(value.emphasised)}`;
        return `        case .${key}: NomoTypeMetrics(size: ${literal(value.size)}, leading: ${literal(value.leading)}, weight: .${identifier(value.weight)}, emphasised: ${emphasised})`;
      })
      .join("\n");
  return section(
    "NomoTypeRole",
    [
      "/// A type role, mapped to the built-in style each platform has for it.",
      "///",
      "/// The sizes are the built-in styles the guideline quotes, not sizes NOMO",
      "/// picks. A surface asks for the role and the platform's semantic font does",
      "/// the rest, so the whole surface scales with Dynamic Type.",
      "public enum NomoTypeRole: String, CaseIterable, Sendable {",
      ...roles.map(([key]) => `    case ${identifier(key)}`),
      "}",
      "",
      "/// A weight, as the document spells it.",
      "public enum NomoTypeWeight: String, CaseIterable, Sendable {",
      ...weights.map((weight) => `    case ${identifier(weight)}`),
      "}",
      "",
      "/// One role on one platform: the quoted size, the leading that goes with",
      "/// it, and the weight, plus the weight the emphasised style uses when the",
      "/// document records one.",
      "public struct NomoTypeMetrics: Equatable, Hashable, Sendable {",
      "    public let size: Double",
      "    public let leading: Double",
      "    public let weight: NomoTypeWeight",
      "    public let emphasised: NomoTypeWeight?",
      "",
      "    public init(size: Double, leading: Double, weight: NomoTypeWeight, emphasised: NomoTypeWeight? = nil) {",
      "        self.size = size",
      "        self.leading = leading",
      "        self.weight = weight",
      "        self.emphasised = emphasised",
      "    }",
      "}",
      "",
      "public extension NomoTypeRole {",
      "    /// The iOS and iPadOS metrics for the role.",
      "    var ios: NomoTypeMetrics {",
      "        switch self {",
      metrics("ios"),
      "        }",
      "    }",
      "",
      "    /// The macOS metrics for the role. The two platforms are quoted",
      "    /// separately because they are one step tighter, and using one table",
      "    /// for both is what makes a shared screen feel wrong on one of them.",
      "    var macOS: NomoTypeMetrics {",
      "        switch self {",
      metrics("macos"),
      "        }",
      "    }",
      "",
      "    /// The metrics for one platform.",
      "    func metrics(for platform: NomoPlatform) -> NomoTypeMetrics {",
      "        switch platform {",
      "        case .iOS: ios",
      "        case .macOS: macOS",
      "        }",
      "    }",
      "",
      ...comment(
        `The smallest legible size the document states for each platform: ${literal(tokens.type.minimumPx.ios)} on iOS and iPadOS, ${literal(tokens.type.minimumPx.macos)} on macOS.`,
        "    ",
      ),
      `    static let iosMinimumSize: Double = ${literal(tokens.type.minimumPx.ios)}`,
      `    static let macOSMinimumSize: Double = ${literal(tokens.type.minimumPx.macos)}`,
      "}",
    ].join("\n"),
  );
}

/** The spacing rhythm as an ordered array, with a name per step. */
function spacing(tokens) {
  const { rhythm, contentGap, sectionGap, measure } = tokens.spacing;
  return section(
    "NomoSpacing",
    [
      "/// The spacing tokens. The values are generated; the rules about them are",
      "/// not, and live beside them in the target.",
      "public enum NomoSpacing {}",
      "",
      "public extension NomoSpacing {",
      "    /// The 4 point rhythm, in the document's order. A spacing value that is",
      "    /// not in here is a defect, which is what `isOnRhythm` is for.",
      `    static let rhythm: [CGFloat] = ${list(rhythm)}`,
      ...rhythm.flatMap((value) => [
        `    /// Step ${value / 4} of the 4 point scale.`,
        `    static let step${value / 4}: CGFloat = ${literal(value)}`,
      ]),
      "    /// The named steps, so a caller can walk them without repeating the",
      "    /// list, and so a name and the array it names cannot drift apart.",
      `    static let steps: [CGFloat] = [${rhythm.map((value) => `step${value / 4}`).join(", ")}]`,
      "    /// Standard horizontal spacing, which the guideline states outside the",
      "    /// rhythm.",
      `    static let contentGap: CGFloat = ${literal(contentGap)}`,
      "    /// The minimum vertical spacing between unrelated content groups, also",
      "    /// stated outside the rhythm.",
      `    static let sectionGap: CGFloat = ${literal(sectionGap)}`,
      "    /// The guideline's unfocused content widths, widest first. A surface",
      "    /// picks the one that fits its column rather than the platform.",
      `    static let measureSteps: [CGFloat] = ${list(measure.steps)}`,
      "}",
    ].join("\n"),
  );
}

/** The radius roles, and the rule that a nested corner takes a smaller one. */
function radii(tokens) {
  const roles = Object.entries(tokens.radii.roles);
  return section(
    "NomoRadiusRole",
    [
      "/// What a radius rounds. A role is named for the element it belongs to,",
      "/// because corners are concentric with the element that contains them and",
      "/// a single radius cannot express that.",
      "public enum NomoRadiusRole: String, CaseIterable, Sendable {",
      ...roles.map(([key]) => `    case ${identifier(key)}`),
      "}",
      "",
      "public extension NomoRadiusRole {",
      "    /// The radius in points, from the document.",
      "    var radius: CGFloat {",
      "        switch self {",
      ...roles.map(([key, value]) => `        case .${key}: ${literal(value)}`),
      "        }",
      "    }",
      "}",
      "",
      "public enum NomoRadii {}",
      "",
      "public extension NomoRadii {",
      ...roles.map(
        ([key]) =>
          `    static var ${key}: CGFloat { NomoRadiusRole.${key}.radius }`,
      ),
      "",
      "    /// Every role with its radius, smallest corner first. A surface reads",
      "    /// the order to pick the role that matches the element it is drawing.",
      "    static var bySize: [(role: NomoRadiusRole, radius: CGFloat)] {",
      "        NomoRadiusRole.allCases",
      "            .map { (role: $0, radius: $0.radius) }",
      "            .sorted { $0.radius < $1.radius }",
      "    }",
      "}",
    ].join("\n"),
  );
}

/** The control size floors. */
function control(tokens) {
  return section(
    "NomoControlMetrics",
    [
      "public enum NomoControlMetrics {}",
      "",
      "public extension NomoControlMetrics {",
      "    /// The hit target floor on iOS and iPadOS, in points.",
      `    static let touchPoints: CGFloat = ${literal(tokens.control.touchPt)}`,
      "    /// The pointer target on macOS, in points.",
      `    static let macOSPoints: CGFloat = ${literal(tokens.control.macosPt)}`,
      "    /// The absolute floor on macOS, in points.",
      `    static let macOSMinimumPoints: CGFloat = ${literal(tokens.control.macosMinimumPt)}`,
      "    /// The same touch rule as CSS pixels, for the web control plane.",
      `    static let webTouchPixels: CGFloat = ${literal(tokens.control.webTouchPx)}`,
      "}",
    ].join("\n"),
  );
}

/** The contrast pairs, with the minimum each one has to clear. */
function contrast(tokens) {
  return section(
    "NomoContrastPair",
    [
      "/// A pairing the document requires, and the ratio it has to reach.",
      "public struct NomoContrastPair: Equatable, Hashable, Sendable {",
      "    public let name: String",
      "    public let foreground: NomoColorRole",
      "    public let background: NomoColorRole",
      "    public let minimum: Double",
      "",
      "    public init(name: String, foreground: NomoColorRole, background: NomoColorRole, minimum: Double) {",
      "        self.name = name",
      "        self.foreground = foreground",
      "        self.background = background",
      "        self.minimum = minimum",
      "    }",
      "}",
      "",
      "public enum NomoContrastPairs {}",
      "",
      "public extension NomoContrastPairs {",
      "    /// Every pairing the document gates, in its own order.",
      "    static let all: [NomoContrastPair] = [",
      ...tokens.colour.contrast.map(
        (pair) =>
          `        NomoContrastPair(name: ${JSON.stringify(pair.name)}, foreground: .${identifier(pair.foreground)}, background: .${identifier(pair.background)}, minimum: ${literal(pair.minimum)}),`,
      ),
      "    ]",
      "}",
    ].join("\n"),
  );
}

/** The whole generated file, as text. */
export function renderSwift(tokens) {
  return [
    HEADER,
    "",
    BEGIN,
    "",
    "import Foundation",
    "",
    colours(tokens),
    "",
    shadows(tokens),
    "",
    type(tokens),
    "",
    spacing(tokens),
    "",
    radii(tokens),
    "",
    control(tokens),
    "",
    contrast(tokens),
    "",
    END,
    "",
  ].join("\n");
}

/** Reads the document and writes the module. Returns the text it wrote. */
export function generate() {
  const source = readFileSync(
    new URL(`../../${SOURCE}`, import.meta.url),
    "utf8",
  );
  const text = renderSwift(JSON.parse(source));
  const target = new URL(`../../${TARGET}`, import.meta.url);
  mkdirSync(dirname(fileURLToPath(target)), { recursive: true });
  writeFileSync(target, text);
  return text;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  generate();
}
